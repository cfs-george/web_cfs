import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const origin = 'https://cyberfreaksoftware.co.uk';
const root = fileURLToPath(new URL('../', import.meta.url));
const brand = 'Cyberfreak Software';
const orgId = origin + '/#organization';
const siteId = origin + '/#website';
const defaultImage = '/images/cfs_logo_dark.png';
export const escapeHtml = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
export const jsonLd = value => JSON.stringify(value, null, 2).replaceAll('<', '\\u003c').replaceAll('>', '\\u003e').replaceAll('&', '\\u0026');

export function renderHead(file, page) {
  if (!page.title || !page.description || !page.name) throw new Error(`${file}: title, description and name are required`);
  const url = new URL(file.replace(/(^|\/)index\.html$/, '$1'), origin + '/').href;
  const canonical = new URL(page.canonical || url, origin);
  if (canonical.origin !== origin || canonical.hash || canonical.search) throw new Error(`${file}: invalid CFS canonical URL`);
  const image = new URL(page.image || defaultImage, origin).href;
  const imageAlt = page.imageAlt || 'Cyberfreak Software logo';
  const organization = {
    '@type': 'Organization', '@id': orgId, name: brand,
    legalName: 'Cyberfreak Software Limited', url: origin + '/',
    logo: { '@type': 'ImageObject', url: origin + defaultImage },
    description: 'SEO management, branded booking websites and independent software projects.',
    sameAs: ['https://www.instagram.com/cfs_george/', 'https://www.linkedin.com/company/cyberfreak-software-ltd', 'https://www.youtube.com/@cyberfreaksoftware', 'https://www.tiktok.com/@cyberfreaksoftware', 'https://x.com/cfs_george']
  };
  const website = { '@type': 'WebSite', '@id': siteId, name: brand, url: origin + '/', publisher: { '@id': orgId }, inLanguage: 'en-GB' };
  const webpage = {
    '@type': page.type || 'WebPage', '@id': canonical.href + '#webpage',
    url: canonical.href, name: page.title, description: page.description,
    isPartOf: { '@id': siteId }, publisher: { '@id': orgId }, inLanguage: 'en-GB'
  };
  const graph = [organization, website, webpage];
  if (file !== 'index.html') {
    webpage.breadcrumb = { '@id': canonical.href + '#breadcrumb' };
    graph.push({ '@type': 'BreadcrumbList', '@id': canonical.href + '#breadcrumb', itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: origin + '/' },
      { '@type': 'ListItem', position: 2, name: page.name, item: canonical.href }
    ] });
  }
  if (page.service) {
    webpage.mainEntity = { '@id': canonical.href + '#service' };
    graph.push({ '@type': 'Service', '@id': canonical.href + '#service', ...page.service, description: page.description, url: canonical.href, provider: { '@id': orgId } });
  }
  if (page.blog) {
    webpage.mainEntity = { '@id': canonical.href + '#blog' };
    graph.push({ '@type': 'Blog', '@id': canonical.href + '#blog', name: brand + ' Blog', url: canonical.href, description: page.description, publisher: { '@id': orgId }, inLanguage: 'en-GB' });
  }
  if (page.article) {
    const { headline, datePublished, author, dateModified } = page.article;
    if (!headline || !datePublished || !author?.name || !page.image) throw new Error(`${file}: articles require headline, datePublished, author and a page-specific image`);
    for (const date of [datePublished, dateModified].filter(Boolean)) {
      if (!/^\d{4}-\d{2}-\d{2}(?:T.*(?:Z|[+-]\d{2}:\d{2}))?$/.test(date) || Number.isNaN(Date.parse(date))) throw new Error(`${file}: invalid article date`);
    }
    webpage.mainEntity = { '@id': canonical.href + '#article' };
    graph.push({ '@type': 'BlogPosting', ...page.article, '@id': canonical.href + '#article', mainEntityOfPage: { '@id': webpage['@id'] }, image, publisher: { '@id': orgId }, inLanguage: 'en-GB' });
  }
  // Additional page-specific schema must describe content present on the page.
  if (page.schema) graph.push(...(Array.isArray(page.schema) ? page.schema : [page.schema]));
  const meta = (name, value, property = false) => `<meta ${property ? 'property' : 'name'}="${escapeHtml(name)}" content="${escapeHtml(value)}">`;
  const tags = [
    '<!-- SEO: generated by scripts/generate-headmeta.mjs; edit seo/pages.json -->',
    '<meta charset="UTF-8">',
    meta('viewport', 'width=device-width, initial-scale=1.0, maximum-scale=5.0'),
    meta('color-scheme', 'dark'), meta('theme-color', '#111111'),
    `<title>${escapeHtml(page.title)}</title>`, meta('description', page.description),
    meta('robots', page.robots || 'index,follow,max-image-preview:large'),
    `<link rel="canonical" href="${escapeHtml(canonical.href)}">`,
    '<link rel="icon" type="image/svg+xml" href="/images/cfs_logo_dark_short.svg">',
    '<link rel="preconnect" href="https://cdnjs.cloudflare.com">',
    '<link rel="preconnect" href="https://fonts.googleapis.com">',
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    ...Object.entries({ title: page.title, description: page.description, url: canonical.href, type: page.article ? 'article' : (page.ogType || 'website'), site_name: brand, locale: 'en_GB', image, 'image:type': 'image/png', 'image:alt': imageAlt }).filter(([key]) => key !== 'image:type' || image.endsWith('.png')).map(([key,value]) => meta('og:' + key,value,true)),
    ...Object.entries({ card: 'summary', title: page.title, description: page.description, image, 'image:alt': imageAlt, site: '@cfs_george' }).map(([key,value]) => meta('twitter:' + key,value))
  ];
  if (page.article) {
    tags.push(meta('article:published_time',page.article.datePublished,true));
    if (page.article.dateModified) tags.push(meta('article:modified_time',page.article.dateModified,true));
  }
  tags.push(`<script type="application/ld+json">\n${jsonLd({ '@context': 'https://schema.org', '@graph': graph })}\n</script>`, '<!-- /SEO -->');
  return tags.join('\n');
}

export async function generate() {
  const pages = JSON.parse((await readFile(path.join(root, 'seo/pages.json'), 'utf8')).replace(/^\uFEFF/, ''));
  // Fail a deployment if a new public HTML page has no metadata configuration.
  async function checkDirectory(dir = root) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || ['node_modules','views','scripts','seo','_site','coverage'].includes(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) await checkDirectory(full);
      else if (entry.isFile() && entry.name.endsWith('.html') && entry.name !== '404.html') {
        const file = path.relative(root, full).split(path.sep).join('/');
        if (!pages[file]) throw new Error(`Missing SEO configuration for ${file}`);
      }
    }
  }
  await checkDirectory();
  const updates = [];
  for (const [file,page] of Object.entries(pages)) {
    if (path.isAbsolute(file) || file.split('/').includes('..') || !file.endsWith('.html')) throw new Error(`Invalid page path: ${file}`);
    let html = await readFile(path.join(root,file),'utf8');
    const head = html.match(/<head>([\s\S]*?)<\/head>/i);
    if (!head) throw new Error(`${file}: missing head`);
    let preserved = head[1].replace(/<!-- SEO: generated[\s\S]*?<!-- \/SEO -->/g,'');
    // On initial migration, remove only the tags now owned by this template.
    preserved = preserved.replace(/<title\b[^>]*>[\s\S]*?<\/title>/gi,'')
      .replace(/<meta\b[^>]*>/gi, tag => /\bcharset\s*=|\b(?:name|property)\s*=\s*["'](?:viewport|description|robots|color-scheme|theme-color|og:[^"']+|twitter:[^"']+|article:[^"']+)["']/i.test(tag) ? '' : tag)
      .replace(/<link\b[^>]*>/gi, tag => /\brel\s*=\s*["'](?:canonical|icon|preconnect)["']/i.test(tag) ? '' : tag);
    html = html.replace(head[0], `<head>\n${renderHead(file,page)}\n${preserved.trim()}\n</head>`);
    if (file !== 'index.html' && !html.includes('aria-label="Breadcrumb"')) {
      const breadcrumb = `<nav aria-label="Breadcrumb" class="breadcrumbs"><a href="/">Home</a> <span aria-hidden="true">/</span> <span aria-current="page">${escapeHtml(page.name)}</span></nav>`;
      html = html.replace(/(<main\b[^>]*>)/i, `$1\n${breadcrumb}`);
    }
    updates.push([file,html]);
  }
  for (const [file,html] of updates) await writeFile(path.join(root,file),html);
  console.log(`Generated SEO metadata for ${updates.length} pages.`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await generate();
